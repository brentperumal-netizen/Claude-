// Scans assets/character/<category>/*.png and regenerates src/data/contentManifest.ts.
// Metro needs statically-analyzable require() calls, so this writes out one
// literal require() per file rather than resolving paths at runtime.
// Run after adding/removing/renaming any file under assets/character/.
const fs = require('fs');
const path = require('path');

const ASSETS_ROOT = path.join(__dirname, '..', 'assets', 'character');
const OUT_FILE = path.join(__dirname, '..', 'src', 'data', 'contentManifest.ts');

const CATEGORY_LABELS = {
  accessories: 'Accessories',
  body_decor: 'Body Decor',
  body_parts: 'Body Parts',
  bottom: 'Bottoms',
  decor_bg_front: 'Scene Decor',
  dress: 'Dresses',
  face_items: 'Face Items',
  hand_weapons: 'Hand Items',
  jacket: 'Jackets',
  shoes: 'Shoes',
  socks: 'Socks',
  top: 'Tops',
  top_underwear: 'Top Underwear',
};

function naturalSort(a, b) {
  const na = parseInt(a, 10);
  const nb = parseInt(b, 10);
  if (!isNaN(na) && !isNaN(nb) && na !== nb) return na - nb;
  return a.localeCompare(b);
}

const categories = fs
  .readdirSync(ASSETS_ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

let requireIndex = 0;
const requireLines = [];
const categoryBlocks = [];

for (const category of categories) {
  const dir = path.join(ASSETS_ROOT, category);
  const files = fs
    .readdirSync(dir)
    .filter((f) => f.toLowerCase().endsWith('.png'))
    .sort(naturalSort);

  const items = files.map((file) => {
    const varName = `img${requireIndex++}`;
    const id = file.replace(/\.png$/i, '');
    requireLines.push(`const ${varName} = require('../../assets/character/${category}/${file}');`);
    return { id, varName };
  });

  categoryBlocks.push({ category, items });
}

const categoryUnion = categories.map((c) => `'${c}'`).join(' | ');

const itemArrays = categoryBlocks
  .map(({ category, items }) => {
    const entries = items
      .map(({ id, varName }) => `    { id: '${id}', category: '${category}', source: ${varName} },`)
      .join('\n');
    return `  ${category}: [\n${entries}\n  ],`;
  })
  .join('\n');

const labelEntries = categories.map((c) => `  ${c}: '${CATEGORY_LABELS[c] ?? c}',`).join('\n');

const output = `// AUTO-GENERATED by scripts/generate-content-manifest.js — do not edit by hand.
// Regenerate with: node scripts/generate-content-manifest.js

${requireLines.join('\n')}

export type ContentCategory = ${categoryUnion};

export interface ContentItem {
  id: string;
  category: ContentCategory;
  source: number;
}

export const CATEGORY_LABELS: Record<ContentCategory, string> = {
${labelEntries}
};

export const CONTENT_ITEMS: Record<ContentCategory, ContentItem[]> = {
${itemArrays}
};

export const CONTENT_CANVAS_WIDTH = 800;
export const CONTENT_CANVAS_HEIGHT = 1200;
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, output);

const total = categoryBlocks.reduce((sum, c) => sum + c.items.length, 0);
console.log(`Wrote ${OUT_FILE}`);
console.log(`${categories.length} categories, ${total} items total.`);
